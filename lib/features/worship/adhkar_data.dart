/// الأذكار مأخوذة من الأحاديث الصحيحة المشهورة (حصن المسلم)، وكل ذِكر معاه مصدره.
/// قاعدة المشروع: ممنوع إضافة ذِكر من غير مصدر.
class Dhikr {
  const Dhikr(this.text, this.count, this.source, {this.note});
  final String text;
  final int count;
  final String source;
  final String? note;
}

class AdhkarGroup {
  const AdhkarGroup(this.id, this.title, this.items);
  final String id;
  final String title;
  final List<Dhikr> items;
}

